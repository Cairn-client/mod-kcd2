<#
.SYNOPSIS
    WO-172: synthetic test for the Lua halves (the dead-copy mark, riding repair, the black and the HUD, the trade hold, the joiner's pickpocket). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO172Synthetic.lua. Live evidence: docs/WO-172-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO172Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO172Synthetic.lua') `
    -Title 'WO-172 synthetic game-side Lua test'
exit $LASTEXITCODE
