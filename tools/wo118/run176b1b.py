"""WO-176 B1(b) live harness (never shipped; no input): the synthetic joiner's real hits (mp_real_hits) on an armed camp bandit that
fights the figure. Host role (the agent already runs as the host). Staging (a camp bandit idles beside a figure -- WO-173): the bandit
is first engaged by the host's pair lever (mp_w163_probe pair, WO-165 P6) with Henry behind the figure; the joiner's first blow makes
WO-136's own retarget hand it to the figure (a fighting NPC); then the pair is released and Henry leaves. The bandit's health is topped
up by the harness (its own block rules untouched) so one engagement takes every blow.

usage: python run176b1b.py <bandit n> [blows] [every_s]   -> logs/run176.b1join.<n>.json (+ run176.b1b.jsonl)
"""
import json, math, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import live
import run165 as R
import run176 as T
import game_input as gi


def run(n, blows=40, every=2.0, row=T.PLAIN):
    name = 'tapo_kasparBandit_%d' % n
    tag = 'b1join.%d' % n
    ax, ay = 2700.0, 2600.0
    az = T.ground(ax, ay)
    gx, gy = ax - 1.1, ay - 1.3      # the figure beside Henry, both in front of the bandit
    gz = T.ground(gx, gy)
    hx, hy = ax + 0.6, ay - 1.5
    hz = T.ground(hx, hy)
    t0 = 18
    total = t0 + blows * every + 20
    L = ['# WO-176 B1b (generated by run176b1b.py): host role; the synthetic joiner figure on open ground, %s engaged on it' % name, 'start 3',
         'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz), 'gcombat 5 %d 1' % total,
         'jhit %d %s %s 450 10.0 25.0 %.2f %d' % (t0, name, row, every, blows)]
    plan = os.path.join(live.LOGS, 'plan.run176.%s.txt' % tag)
    open(plan, 'w').write('\n'.join(L) + '\n')
    n0 = T.nlen()
    t0s = T.stamp()
    R.peer(tag, plan, ['--duration', str(int(total + 10))])
    tp = time.time()
    phase, moves, tops = 0, 0, 0
    while time.time() - tp < total + 12:
        el = time.time() - tp
        if phase == 0 and el > 9:
            for _ in range(2):
                live.lua('local e=System.GetEntityByName("%s"); if e then e:SetWorldPos({x=%f, y=%f, z=%f}) end; '
                         'player:SetWorldPos({x=%f, y=%f, z=%f}); player:SetWorldAngles({x=0, y=0, z=0})' % (name, ax, ay, az + 0.2, hx, hy, hz + 0.2))
                time.sleep(0.5)
            live.cmd('mp_w163_probe pair %s on 1' % name)
            # the fight is started the way it starts in (a): Henry's own blow (real input under the policy), then Henry stays passive
            g = gi.Game('wo176-b1b-start-the-fight')
            try:
                g.front(); g.release_all()
                g.tap('1', 120); time.sleep(1.8)
                for _ in range(2):
                    g.click('left', 90); time.sleep(1.3)
            except gi.NotFocused as e:
                print('input stopped:', e)
            finally:
                g.release_all(); time.sleep(0.5); g.back()
            phase = 2
        if phase >= 1:
            st = T.bandit_state(name)
            if st and st[2]: break
            if st and st[0] < 60:
                live.lua('local e=System.GetEntityByName("%s"); if e then e.soul:SetState("health", 100) end' % name); tops += 1
            if st and st[3] < 70:
                live.lua('player.soul:SetState("health", 100)')
            if st and phase == 2 and math.hypot(st[4] - ax, st[5] - ay) > 6 and moves < 30:
                live.lua('local e=System.GetEntityByName("%s"); if e then e:SetWorldPos({x=%f, y=%f, z=%f}) end' % (name, ax, ay, az + 0.2)); moves += 1
        time.sleep(1.5)
    live.cmd('mp_w163_probe pair %s off' % name)
    live.lua('local p=player:GetWorldPos(); player:SetWorldPos({x=p.x - 250, y=p.y - 250, z=p.z + 40})')   # the fight ends before any load
    time.sleep(3)
    nat = T.nlines_from(n0)
    hits = [l for l in nat if 'WO173-HIT npc=%s seq=' % name in l]
    res = {'tag': tag, 'window': [t0s, T.stamp()], 'bandit': name, 'blows_planned': blows, 'wo173_hit_lines': len(hits),
           'bandit_moved_back': moves, 'bandit_topped_up': tops}
    for k in ('engine', 'fallback', 'reaction', 'knockdown', 'state'):
        d = {}
        for l in hits:
            m = re.search(r'\b' + k + r'=(\S+)', l)
            v = m.group(1) if m else '?'
            d[v] = d.get(v, 0) + 1
        res[k] = d
    res['bandit_blows_on_figure'] = sum('WO132-HITS npc hit on avatar' in l for l in nat)
    res['bandit_blows_on_henry'] = sum('WO176-HITME' in l for l in nat)
    res['dup'] = sum('applied=dup' in l for l in nat)
    res['faults'] = [l.strip()[15:200] for l in nat if ('FAULT' in l and 'FAULT-SUM' not in l) or 'faulted' in l or 'switched off' in l][:5]
    res['samples'] = [l.strip()[15:330] for l in hits[:3]]
    json.dump(res, open(os.path.join(live.LOGS, 'run176.%s.json' % tag), 'w'), indent=1)
    with open(os.path.join(live.LOGS, 'run176.b1b.jsonl'), 'a') as f:
        f.write(json.dumps(res) + '\n')
    print(json.dumps(res))
    return res


if __name__ == '__main__':
    run(int(sys.argv[1]), int(sys.argv[2]) if len(sys.argv) > 2 else 40, float(sys.argv[3]) if len(sys.argv) > 3 else 2.0)
