def klen():
    return FT.klog_len()


def klines(n0, pat):
    new, _ = FT.klog_since(n0)
    rx = re.compile(pat)
    return [l.strip() for l in new if rx.search(l)]


def flines(path, pat):
    try:
        txt = open(path, encoding='utf-8', errors='replace').read().splitlines()
    except OSError:
        return []
    rx = re.compile(pat)
    return [l.strip() for l in txt if rx.search(l)]


def nudge():
    """The mod writes a state frame only when the player moves (a heartbeat every ~10 s otherwise) and the agent waits 6 s for the
    first one before it falls back to HTTP (no mod events): a half-metre step right before an agent starts."""
    live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + 0.5, y = p.y, z = p.z + 0.2})')
    time.sleep(0.6)


def wait_until(t_abs):
    d = t_abs - time.time()
    if d > 0: time.sleep(d)


