"""WO-167 live harness (never shipped). Unattended: no focus change, no key press, the game minimised, the throwaway playline only.
Uses run165.py (relay / peer / agent / stop) and ft167.py (the travel probe's readers and the escape).

usage:
  python run167.py ftj <agent.dll>    FT2/FT4, this game as the JOINER of the synthetic host: the host's travel run here (the switch let
                                      go and taken back), a blind start (a quest's travel), a refusal, two picks asked of the host
  python run167.py fth <agent.dll>    FT2/FT3/FT4, this game as the HOST of a synthetic joiner: its pick travelled to, unknown and off
                                      refused, this game's own (quest) travel told to the joiner, a road event's stop told as interrupted
"""
import json, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import live
import run165 as R
import ft167 as FT

VILLAGE = (2338.0, 2048.3, 109.2)
FAR = (2792.0, 2302.9, 118.2)   # 520 m away on the road (the WO-167 probes: a travel lands exactly here)


def klen():
    return FT.klog_len()


def klines(n0, pat):
    new, _ = FT.klog_since(n0)
    rx = re.compile(pat)
    return [l.strip() for l in new if rx.search(l)]


def flines(path, pat):
    try:
        txt = open(path, encoding='utf-8', errors='replace').read().splitlines()
    except OSError:
        return []
    rx = re.compile(pat)
    return [l.strip() for l in txt if rx.search(l)]


def nudge():
    """The mod writes a state frame only when the player moves (a heartbeat every ~10 s otherwise) and the agent waits 6 s for the
    first one before it falls back to HTTP (no mod events): a half-metre step right before an agent starts."""
    live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + 0.5, y = p.y, z = p.z + 0.2})')
    time.sleep(0.6)


def wait_until(t_abs):
    d = t_abs - time.time()
    if d > 0: time.sleep(d)


def ftj(agent_dll):
    R.stop('agent'); R.stop('peer')
    time.sleep(5)
    FT.escape()
    s = ' '.join
    plan = ['# WO-167 FT joiner role (generated by run167.py): the synthetic host travels; this game runs the same travel',
            'start 10',
            'ghost 2341.0 2051.0 108.6 0 1 2 0.0005 30',
            'w164 25 6 s 1 %.1f,%.1f,%.1f' % FAR,
            'w164 50 6 e 1 %.1f,%.1f,%.1f 0' % FAR,
            'w164 65 6 s 2 -',
            'w164 67 6 e 2 %.1f,%.1f,%.1f 0' % VILLAGE,
            'w164 80 6 n 7 combat']
    path = os.path.join(live.LOGS, 'plan.run167.ftj.txt')
    open(path, 'w').write('\n'.join(plan) + '\n')
    n0 = klen()
    R.peer('r167ftj', path, ['--duration', '115', '--claim-host'])
    t0 = time.time() + 10.0   # the plan's stream clock (start 10)
    nudge()
    R.agent('r167ftj', agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    res = {'samples': {}}
    wait_until(t0 + 18); res['samples']['t18_before'] = FT.state()
    wait_until(t0 + 29); res['samples']['t29_running'] = FT.state()
    wait_until(t0 + 40); res['samples']['t40_after'] = FT.state()
    wait_until(t0 + 47); res['samples']['t47_after'] = FT.state()
    wait_until(t0 + 55); FT.escape(); res['samples']['t58_back'] = FT.state()
    wait_until(t0 + 72); res['samples']['t72_blind'] = FT.state()
    wait_until(t0 + 90)
    live.lua('KCD2MP_W167FtPicked("ttkc_man_31", "OnDoubleClicked")')
    wait_until(t0 + 94)
    live.lua('KCD2MP_W167FtPicked("1234567", "OnDoubleClicked")')
    wait_until(t0 + 100)
    st = R.load_state()
    res['kcd'] = klines(n0, r'WO167-FT|FastTravel: |WO114-FASTTRAVEL|MP-TOAST|WO154-FT|ApseOpen|Setting active random event|stopping FastTravel')
    res['agent'] = flines(st.get('agentlog', ''), r'WO167-FT|MP-LEASH joiner|WO164-TEST')
    res['peer'] = flines(st.get('peerlog', ''), r'SYNTH got W164|kind=6|connected|refused')
    out = os.path.join(live.LOGS, 'run167.ftj.json')
    json.dump(res, open(out, 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps(res, indent=1)[:12000])


def release_joiner_hold():
    """A joiner run's agent killed mid-session never gives back WO-114's hold: the engine's switch stays 0 (the harness gives it back)."""
    live.lua('if KCD2MP_Wo114FastTravelBlock then KCD2MP_Wo114FastTravelBlock(false, "harness") end')
    live.cmd('wh_pl_FastTravelEnabled 1')


def fth(agent_dll):
    R.stop('agent'); R.stop('peer')
    time.sleep(5)
    release_joiner_hold()
    FT.escape()
    plan = ['# WO-167 FT host role (generated by run167.py): the synthetic joiner picks; this game travels',
            'start 10',
            'w164h 15 6 r 1 %.1f,%.1f,%.1f' % FAR,
            'w164h 45 6 r 2 -',
            'w164h 60 6 r 3 %.1f,%.1f,%.1f' % VILLAGE]
    path = os.path.join(live.LOGS, 'plan.run167.fth.txt')
    open(path, 'w').write('\n'.join(plan) + '\n')
    n0 = klen()
    live.cmd('wh_pl_RandomEventsAutoSpawnEnabled 0')   # the picks' travels without road events (an ambush kills an unattended character)
    nudge()
    R.agent('r167fth', agent_dll, [])   # the agent first: in a shared world it claims host and is the authority
    time.sleep(8)
    R.peer('r167fth', path, ['--duration', '200'])
    t0 = time.time() + 10.0
    res = {'samples': {}}
    wait_until(t0 + 13); res['samples']['t13_before'] = FT.state()
    wait_until(t0 + 30); res['samples']['t30_after_pick'] = FT.state()
    wait_until(t0 + 36); FT.escape(); res['samples']['t40_back'] = FT.state()
    wait_until(t0 + 55); live.cmd('mp_fast_travel off')
    wait_until(t0 + 68); live.cmd('mp_fast_travel on')
    # this game's own travel that no pick named (a quest's or the console's): the joiner told "-", then the end
    wait_until(t0 + 75)
    live.cmd('wh_pl_FakeFastTravelTo %.1f %.1f %.1f' % FAR)
    wait_until(t0 + 92); res['samples']['t92_fake'] = FT.state()
    FT.escape()
    # a road event stops this game's travel midway (the probes' route: the ambush at the bushy slope fires with events on)
    wait_until(t0 + 100)
    nr = klen()
    live.cmd('wh_pl_RandomEventsAutoSpawnEnabled 1')
    live.cmd('wh_pl_FastTravelTo %.1f %.1f %.1f' % FAR)
    stop_at = time.time() + 60
    ev = None
    while time.time() < stop_at:
        ls = klines(nr, r'Setting active random event for fast travel|FastTravel: ended')
        if any('FastTravel: ended' in l for l in ls):
            ev = [l for l in ls if 'random event' in l]
            break
        time.sleep(0.5)
    FT.escape()
    live.cmd('wh_pl_RandomEventsAutoSpawnEnabled 1')
    res['road_event'] = ev
    res['samples']['after_road'] = FT.state()
    time.sleep(6)
    st = R.load_state()
    res['kcd'] = klines(n0, r'WO167-FT|FastTravel: |WO114-FASTTRAVEL|MP-TOAST|WO154-FT|ApseOpen|Setting active random event|stopping FastTravel|mp_fast_travel')
    res['agent'] = flines(st.get('agentlog', ''), r'WO167-FT|MP-LEASH host|WO154')
    res['peer'] = flines(st.get('peerlog', ''), r'SYNTH got W164|kind=6|connected|refused|role=')
    out = os.path.join(live.LOGS, 'run167.fth.json')
    json.dump(res, open(out, 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps(res, indent=1)[:14000])


if __name__ == '__main__':
    v = sys.argv[1]
    if v == 'ftj': ftj(sys.argv[2])
    elif v == 'fth': fth(sys.argv[2])
