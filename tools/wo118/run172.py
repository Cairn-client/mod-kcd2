    release_joiner_hold()
    if not trader:
        s = S.ask('local best, bd = nil, 1e9; local p = player:GetWorldPos(); for _, e in ipairs(System.GetEntitiesInSphere(p, 120) or {}) do '
                  'local ok = false; pcall(function() ok = e.soul and e.soul:HasScriptContext("shop_sellerReadyToSell") == true end); '
                  'if ok then local q = e:GetWorldPos(); local d = (q.x-p.x)^2 + (q.y-p.y)^2; if d < bd then best, bd = e:GetName(), d end end end; '
                  'System.LogAlways("@TAG " .. tostring(best))', 'tr%d' % time.time_ns(), timeout=4.0)
