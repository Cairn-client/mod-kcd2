def horse_probe():
    s = S.ask('local o={} for id,h in pairs(KCD2MP.horseGhosts or {}) do local e=h.entity local p=nil pcall(function() p=e:GetWorldPos() end) '
              'local g=p and System.GetTerrainElevation({x=p.x,y=p.y,z=0}) local m=nil local gh=KCD2MP.ghosts[id] '
              'if gh and KCD2MP_GhostIsMounted then m=KCD2MP_GhostIsMounted(gh) end '
              'o[#o+1]=string.format("%s:%s:z=%.2f:g=%.2f:mounted=%s", tostring(id), tostring(h.worldName or "proxy"), p and p.z or -999, g or -999, tostring(m)) end '
              'local r={} for id,gh in pairs(KCD2MP.ghosts or {}) do r[#r+1]=tostring(id)..":riding="..tostring(gh.istate and gh.istate.isRiding).. ":mounted="..tostring(KCD2MP_GhostIsMounted and KCD2MP_GhostIsMounted(gh)) end '
              'System.LogAlways("@TAG horses=" .. table.concat(o, ",") .. " ghosts=" .. table.concat(r, ","))', 'hp%d' % time.time_ns(), timeout=4.0)
    return s


