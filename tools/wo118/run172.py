"""WO-172 live harness (never shipped). Unattended: no focus change, no key press, the game minimised (a watcher keeps it so), the
throwaway playline only. Uses run165.py (relay / peer / agent / stop), sit165.py's readers and run167.py's rows and rings.

usage:
  python run172.py c1 <agent.dll>     joiner role: two copies fight this player with rows; one dies mid-swing (the stream's dead bit)
                                      while its rows and hand rows keep coming -> the death applied, then nothing worked on the corpse
  python run172.py r1 <agent.dll>     joiner role: the host's figure rides, its mount is taken away here (the field), it dismounts,
                                      remounts and rides through a load -> remounts, the horse never under the ground
  python run172.py ft1 <agent.dll>    joiner role: a quest's own travel refused here, then the host travels and the leash places this
                                      player -> the black lifted (WO172-FT) within 3 s of the placement, the HUD shown
  python run172.py h1 <agent.dll>     joiner role: a trader copy's conversation ends (the trade screen opens): held until the screen's
                                      own close sound, released <= 1 s after; a cancelled haggle releases nothing
  python run172.py w1 <agent.dll>     host role: a synthetic joiner's figure rides, fights and the host travels; the game's own
                                      screenshots (r_GetScreenShot, the window stays minimised) before and after each, for the weapons
  python run172.py shot <tag>         one screenshot, scaled into logs/
Writes logs/run172.<scenario>.json
"""
