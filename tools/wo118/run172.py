SHOTS = os.path.join(os.environ.get('USERPROFILE', ''), 'Saved Games', 'kingdomcome2', 'screenshots')


def shot(tag):
    before = set(os.listdir(SHOTS)) if os.path.isdir(SHOTS) else set()
    live.cmd('r_GetScreenShot 1')
    for _ in range(20):
        time.sleep(0.5)
        new = sorted(set(os.listdir(SHOTS)) - before) if os.path.isdir(SHOTS) else []
        if new:
            time.sleep(1.0)
            src = os.path.join(SHOTS, new[-1])
            out = os.path.join(live.LOGS, 'shot172.%s.jpg' % tag)
            try:
                from PIL import Image
                im = Image.open(src); im.thumbnail((1280, 720)); im.save(out, quality=85)
            except Exception as e:
                return 'scale failed %s' % e
            os.remove(src)   # the game's own screenshots folder keeps only what the maintainer took
            return out
    return None


def kgrep(n0, pat):
    return klines(n0, pat)


