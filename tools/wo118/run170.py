"""WO-170 live harness (never shipped). Unattended: no focus change, no key press, no game action injected; the game minimised; the
throwaway playline only. Uses run165.py (game / inject / relay / peer / agent / stop) and sit165.py's readers.

usage:
  python run170.py f1 <agent.dll> [guard] [secs]
        host role: the synthetic joiner's figure beside a local villager. The joiner never swings (A: mp_figure_guard off = 0.48.5's
        behaviour, B: on), the villager is set on the figure by the joiner's attributed hits (avatarfight, stamina only). Then C: the
        joiner sends 5 Attack actions (the figure's swings), D: 10 more. Counts per window: the villager's health, blows landed on it
        (the DLL's LocalHit), WO170-FIGUREHIT relayed / dropped, the figure's automation lines, the agent's inbound Attack dispatches.
        Writes logs/run170.f1.json
  python run170.py f1b <agent.dll> [guard] [secs]
        host role, two fresh figures (the agent and the peer restarted each time, so the figure binds under that setting): X = mp_figure_guard
        off (0.48.5: the figure's automation is left alone until the partner's combat bit), Y = on with the figure's automation left ON
        (mp_w166_automode 1: the guard's backstop alone -- every blow of the figure's own is put back). Villager health, blows landed
        on it, WO170-FIGUREHIT lines. Writes logs/run170.f1b.json
  python run170.py status               the DLL's and the Lua's WO-170 counters
"""
import json, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import live
import run165 as R
import sit165 as S

ROW = '3e27732b-b152-4a27-97d2-1ebba717a588'   # the WO-165 plans' punch row


def stamp():
    return time.strftime('%H:%M:%S')


def native_window(since, until):
    out = []
    with open(live.NLOG, encoding='utf-8', errors='replace') as f:
        for l in f:
            if len(l) > 12 and l[0] == '[' and l[9] == '.' and since <= l[1:9] <= until: out.append(l)
    return out


def agent_lines_from(path, n0):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read().splitlines()[n0:]


def alen(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return sum(1 for _ in f)


def count(lines, needle):
    return sum(1 for l in lines if needle in l)


def f1(agent_dll, guard='ttkc_man_3', secs=60):
    R.stop('agent'); R.stop('peer')
    time.sleep(7)
    g = S.ent_pos(guard)
    if not g: raise SystemExit('no villager ' + guard)
    gx, gy = g[0] + 1.6, g[1]
    gz = S.ground(gx, gy)
    hx, hy = g[0] - 30.0, g[1]        # Henry 30 m away: no host lock-on, the villager never on him
    hz = S.ground(hx, hy)
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (hx, hy, hz + 0.3)); time.sleep(1.5)
    tA0, tA1 = 30, 30 + secs
    tB0, tB1 = tA1 + 5, tA1 + 5 + secs
    tC = tB1 + 10
    tD = tC + 25
    total = tD + 10 * 3 + 20
    L = ['# WO-170 F1 (generated by run170.py): host role; the synthetic joiner\'s figure beside a villager', 'start 3',
         'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz), 'avatarfight 3 %d %s 2.0 0 3' % (tB1 + 2, guard),
         'gcombat %d %d 1' % (tC - 3, total)]
    for i in range(5): L.append('jattack %d %s' % (tC + i * 3, ROW))
    for i in range(10): L.append('jattack %d %s' % (tD + i * 3, ROW))
    plan = os.path.join(live.LOGS, 'plan.run170.f1.txt')
    open(plan, 'w').write('\n'.join(L) + '\n')
    R.agent('r170f1', agent_dll, [])
    time.sleep(1)
    live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + 0.5, y = p.y, z = p.z + 0.2})')   # a state frame for the agent's 6 s window
    time.sleep(10)
    t_start = time.time()
    R.peer('r170f1', plan, ['--duration', str(total + 60)])
    agentlog = R.load_state()['agentlog']
    peer_t0 = time.time() + 3.0      # the plan's "start 3"

    def at(t):
        d = peer_t0 + t - time.time()
        if d > 0: time.sleep(d)

    res = {'villager': guard, 'secs': secs, 'windows': {}}

    def window(name, t0, t1, guardmode=None):
        at(t0 - 2)
        if guardmode is not None:
            live.cmd('mp_figure_guard %s' % guardmode)
        time.sleep(2)
        hp0 = S.health(guard)
        a0 = alen(agentlog)
        s = stamp()
        at(t1)
        e = stamp()
        hp1 = S.health(guard)
        nat = native_window(s, e)
        ag = agent_lines_from(agentlog, a0)
        w = {'mode': guardmode, 'window': [s, e], 'villager_hp': [hp0, hp1],
             'blows_landed_on_villager': count(nat, 'PIPE: LocalHit'),
             'figure_hits_relayed': count(nat, 'WO170-FIGUREHIT relayed'),
             'figure_hits_dropped': count(nat, 'WO170-FIGUREHIT dropped'),
             'figure_hits_dropped_put_back': sum(1 for l in nat if 'WO170-FIGUREHIT dropped' in l and 'hp -0.00 st -0.00' not in l),
             'villager_blows_on_figure': count(nat, 'WO132-HITS npc hit on avatar'),
             'automation_lines': [l.split('WO121-MOTION ', 1)[1].strip()[:140] for l in nat if 'combat automation' in l and 'WO121-MOTION' in l][-2:],
             'released_lines': [l.split('WO121-MOTION ', 1)[1].strip()[:140] for l in nat if 'released' in l and 'WO121-MOTION body=kcd2mp' in l][-2:],
             'swing_recv': count(ag, 'MP-SWING hop=recv'), 'swing_queued_ok': count(ag, 'MP-SWING hop=queued') and sum(1 for l in ag if 'MP-SWING hop=queued' in l and 'ok=1' in l),
             'inbound_attack_lines': count(ag, 'kind=Attack seq=') and sum(1 for l in ag if 'section=inbound' in l and 'kind=Attack' in l and 'dispatch=swing-queued' in l),
             'native_swings_queued': count(nat, 'SWING: entity=') and sum(1 for l in nat if 'SWING: entity=' in l and 'queued fragment' in l)}
        res['windows'][name] = w
        print(name, json.dumps(w), flush=True)

    window('A_guard_off', tA0, tA1, 'off')
    window('B_guard_on', tB0, tB1, 'on')
    window('C_five_attacks', tC - 2, tC + 5 * 3 + 6, 'on')
    window('D_ten_attacks', tD - 2, tD + 10 * 3 + 6, 'on')
    st = R.load_state()
    live.cmd('mp_w170_status')
    res['agent_stats'] = [l for l in agent_lines_from(agentlog, 0) if 'MP-ACTION section=inbound accepted' in l][-1:]
    res['native_hits_status'] = [l.strip()[:600] for l in native_window('00:00:00', '23:59:59') if 'figure_guard=' in l][-1:]
    json.dump(res, open(os.path.join(live.LOGS, 'run170.f1.json'), 'w'), indent=1)


def f1b(agent_dll, guard='ttkc_man_3', secs=60):
    res = {'villager': guard, 'secs': secs, 'runs': {}}
    R.stop('agent'); R.stop('peer')
    time.sleep(7)
    R.agent('r170f1b', agent_dll, [])      # the agent stays up: the switches are pushed to the DLL (every 10 s) BEFORE each figure binds
    time.sleep(1)
    live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + 0.5, y = p.y, z = p.z + 0.2})')
    time.sleep(12)
    for tag, gmode, amode in (('X_guard_off', 'off', 0), ('Y_backstop_only', 'on', 1)):
        R.stop('peer')
        live.cmd('mp_figure_guard %s' % gmode); live.cmd('mp_w166_automode %d' % amode)
        time.sleep(14)
        g = S.ent_pos(guard)
        gx, gy = g[0] + 1.6, g[1]
        gz = S.ground(gx, gy)
        hx, hy = g[0] - 30.0, g[1]
        hz = S.ground(hx, hy)
        for _ in range(3):
            live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (hx, hy, hz + 0.3)); time.sleep(1.5)
        L = ['# WO-170 F1b (generated by run170.py)', 'start 3', 'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz),
             'avatarfight 3 %d %s 2.0 0 3' % (secs + 40, guard)]
        plan = os.path.join(live.LOGS, 'plan.run170.%s.txt' % tag)
        open(plan, 'w').write(chr(10).join(L) + chr(10))
        R.peer('r170' + tag, plan, ['--duration', str(secs + 80)])
        agentlog = R.load_state()['agentlog']
        time.sleep(20)
        hp0 = S.health(guard)
        s0 = stamp()
        n0 = alen(agentlog)
        time.sleep(secs)
        s1 = stamp()
        hp1 = S.health(guard)
        nat = native_window(s0, s1)
        allnat = native_window('00:00:00', s1)
        hits = [l.strip()[:200] for l in nat if 'PIPE: LocalHit' in l]
        big = [l for l in hits if not re.search(r'LocalHit 0[.]0[0-9] st', l)]
        w = {'guard': gmode, 'automode': amode, 'window': [s0, s1], 'villager_hp': [hp0, hp1],
             'localhits_on_villager': len(hits), 'localhits_over_0_1_hp': len(big), 'localhit_samples': big[:6],
             'villager_blows_on_figure': count(nat, 'WO132-HITS npc hit on avatar'),
             'figurehit_dropped': count(nat, 'WO170-FIGUREHIT dropped'), 'figurehit_relayed': count(nat, 'WO170-FIGUREHIT relayed'),
             'figurehit_samples': [l.strip()[:260] for l in nat if 'WO170-FIGUREHIT' in l][:5],
             'automation_line': [l.split('WO121-MOTION ', 1)[1].strip()[:150] for l in allnat if 'combat automation' in l and 'WO121-MOTION body=kcd2mp' in l][-1:]}
        res['runs'][tag] = w
        print(tag, json.dumps(w), flush=True)
    live.cmd('mp_figure_guard on'); live.cmd('mp_w166_automode 0')
    R.stop('agent'); R.stop('peer')
    json.dump(res, open(os.path.join(live.LOGS, 'run170.f1b.json'), 'w'), indent=1)


def status():
    live.cmd('mp_w170_status')
    for l in live.tail(live.KLOG, 3, 'WO170-STATUS'): print(l[:300])
    for l in live.tail(live.NLOG, 3, 'figure_guard='): print(l[:600])


def riders(agent_dll, n=10, secs=150):
    """F3 (joiner role): n horse + rider pairs streamed by the synthetic host near the player. The horse copies are the world's own parked
    dummyWanderer_horse_N (parked far away, no physics here until written near); the riders do not exist in this world (stand-ins)."""
    R.stop('agent'); R.stop('peer')
    time.sleep(7)
    p = S.player_pos()
    L = ['# WO-170 F3 (generated by run170.py): joiner role, %d horse + rider pairs near the player' % n, 'start 5',
         'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (p[0] + 60.0, p[1], S.ground(p[0] + 60.0, p[1]))]
    for i in range(1, n + 1):
        x, y = p[0] + 12 + 3 * i, p[1] + 6
        z = S.ground(x, y)
        L.append('hold dummyWanderer_horse_%d %.2f %.2f %.2f 0' % (i, x, y, z))
        L.append('hold dummyWanderer_nobleman_man_%d %.2f %.2f %.2f 0' % (i, x + 0.3, y + 0.2, z + 1.2))
    plan = os.path.join(live.LOGS, 'plan.run170.riders.txt')
    open(plan, 'w').write(chr(10).join(L) + chr(10))
    k0 = S.klen()
    R.peer('r170riders', plan, ['--duration', str(secs + 60), '--claim-host'])
    R.agent('r170riders', agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(secs)
    kl = S.kcd_lines(r'WO170-RIDER|WO164-RIDER|WO131-STANDIN|WO136-STANDIN|WO167-STANDIN|Lua error|attempt to', k0)
    res = {'pairs': n, 'secs': secs, 'wo170_wait': sum('WO170-RIDER mount=wait' in l for l in kl), 'wo170_ok': sum('WO170-RIDER mount=ok' in l for l in kl),
           'wo170_gave_up': sum('WO170-RIDER mount=gave-up' in l for l in kl), 'standins': sum('STANDIN spawn' in l for l in kl),
           'lua_errors': [l[:200] for l in kl if 'Lua error' in l or 'attempt to' in l][:5], 'samples': [l.strip()[:240] for l in kl if 'WO170-RIDER' in l][:8],
           'game_alive': live.up()}
    nat = native_window('00:00:00', '23:59:59')
    res['native_faults'] = [l.strip()[:200] for l in nat[-400:] if 'FAULT' in l or 'faulted' in l][:5]
    print(json.dumps(res, indent=1))
    json.dump(res, open(os.path.join(live.LOGS, 'run170.riders.json'), 'w'), indent=1)
    live.cmd('mp_w170_status')


if __name__ == '__main__':
    v = sys.argv[1]
    if v == 'f1': f1(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'ttkc_man_3', int(sys.argv[4]) if len(sys.argv) > 4 else 60)
    elif v == 'f1b': f1b(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'ttkc_man_3', int(sys.argv[4]) if len(sys.argv) > 4 else 60)
    elif v == 'riders': riders(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 10, int(sys.argv[4]) if len(sys.argv) > 4 else 150)
    elif v == 'status': status()

