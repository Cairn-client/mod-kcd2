"""WO-171 live harness (never shipped). Unattended: no focus change, no key press, the game minimised (a watcher keeps it so), the
throwaway playline only. Uses run165.py (relay / peer / agent / stop) and run167.py's readers.

usage:
  python run171.py spin <role> <agent.dll>      the synthetic peer stands and turns clockwise through 360 degrees every 40 s for 90 s:
                                                the partner's pin turns through all eight pictures (role = host: the peer is the joiner,
                                                purple; role = joiner: the peer is the host, red)
  python run171.py circle <role> <agent.dll>    the peer walks a 12 m circle (period 50 s) for 100 s: the pin moves (<= 60 a minute) and turns
  python run171.py load <role> <agent.dll>      the peer stands; a load of the throwaway save at 40 s: the pin goes and comes back
  python run171.py rejoin <role> <agent.dll>    the peer connects, leaves, connects again (same name): the same colour
Writes logs/run171.<scenario>.<role>.json
"""
import json, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import live
import run165 as R
import sit165 as S
from run167 import VILLAGE, nudge, release_joiner_hold, wait_until, flines, klen, klines


def nlines(pat, since=0):
    try:
        with open(live.NLOG, encoding='utf-8', errors='replace') as fh:
            ls = fh.read().splitlines()
    except OSError:
        return []
    rx = re.compile(pat)
    return [l.strip() for l in ls[since:] if rx.search(l)]


def nlen():
    try:
        with open(live.NLOG, 'rb') as fh:
            return fh.read().count(b'\n')
    except OSError:
        return 0


def prelude():
    R.stop('agent'); R.stop('peer')
    time.sleep(5)
    release_joiner_hold()
    z = S.ground(*VILLAGE[:2])
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (VILLAGE[0], VILLAGE[1], z + 0.3)); time.sleep(1.2)
    return z


def start(role, agent_dll, plan_lines, duration, tag):
    path = os.path.join(live.LOGS, 'plan.run171.%s.txt' % tag)
    open(path, 'w').write('\n'.join(plan_lines) + '\n')
    n0, m0 = klen(), nlen()
    if role == 'host':
        R.agent(tag, agent_dll, [])
        time.sleep(1); nudge(); time.sleep(8)
        R.peer(tag, path, ['--duration', str(duration)])
    else:
        R.peer(tag, path, ['--duration', str(duration), '--claim-host'])
        nudge()
        R.agent(tag, agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
        time.sleep(12)
        live.cmd('mp_leash off')
    return n0, m0, time.time()


def finish(res, scenario, role, n0, m0):
    st = R.load_state()
    res['agent'] = flines(st.get('agentlog', ''), r'WO171-|MP-WO171-STATS|WO164-MAPMARK|FAULT')[-120:]
    res['native'] = nlines(r'WO171-|WO164-MAPMARK|WO166-MAPMARK|MP-GRAVE (marker|after the rescan|world changed)|FAULT|ACTIONS: marker', m0)[-120:]
    res['kcd_errors'] = [l[:200] for l in klines(n0, r'Error|FAULT|Exception') if 'AnimFrame' not in l and 'Validator' not in l][-30:]
    live.cmd('mp_w171_status')
    json.dump(res, open(os.path.join(live.LOGS, 'run171.%s.%s.json' % (scenario, role)), 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    release_joiner_hold()
    print(json.dumps({k: (v[-25:] if isinstance(v, list) else v) for k, v in res.items()}, indent=1)[:14000])


def spin(role, agent_dll):
    z = prelude()
    plan = ['# WO-171 spin (generated by run171.py)', 'start 3', 'gspin %.2f %.2f %.2f 40 30' % (VILLAGE[0] + 8, VILLAGE[1] + 6, z)]
    n0, m0, t0 = start(role, agent_dll, plan, 100, 'spin_' + role)
    res = {'scenario': 'spin', 'role': role}
    wait_until(t0 + 100)
    finish(res, 'spin', role, n0, m0)


def circle(role, agent_dll):
    z = prelude()
    plan = ['# WO-171 circle (generated by run171.py)', 'start 3', 'gcircle %.2f %.2f %.2f 12 50 30' % (VILLAGE[0] + 4, VILLAGE[1] + 4, z)]
    n0, m0, t0 = start(role, agent_dll, plan, 110, 'circle_' + role)
    res = {'scenario': 'circle', 'role': role}
    wait_until(t0 + 110)
    finish(res, 'circle', role, n0, m0)


def load(role, agent_dll):
    z = prelude()
    plan = ['# WO-171 load (generated by run171.py)', 'start 3', 'gspin %.2f %.2f %.2f 40 30' % (VILLAGE[0] + 8, VILLAGE[1] + 6, z)]
    n0, m0, t0 = start(role, agent_dll, plan, 120, 'load_' + role)
    res = {'scenario': 'load', 'role': role}
    wait_until(t0 + 40)
    res['load_n'] = nlen()
    R.load('4', 'autosave132')
    wait_until(t0 + 120)
    finish(res, 'load', role, n0, m0)


def rejoin(role, agent_dll):
    z = prelude()
    plan = ['# WO-171 rejoin (generated by run171.py)', 'start 3', 'gspin %.2f %.2f %.2f 40 30' % (VILLAGE[0] + 8, VILLAGE[1] + 6, z)]
    n0, m0, t0 = start(role, agent_dll, plan, 40, 'rejoin1_' + role)
    res = {'scenario': 'rejoin', 'role': role}
    wait_until(t0 + 30)
    R.stop('peer')
    time.sleep(20)                                   # the partner is gone: its pin removed (WO164: 10 s without a position)
    path = os.path.join(live.LOGS, 'plan.run171.rejoin2_%s.txt' % role)
    open(path, 'w').write('\n'.join(plan) + '\n')
    R.peer('rejoin2_' + role, path, ['--duration', '50'] + (['--claim-host'] if role == 'joiner' else []))
    t1 = time.time()
    wait_until(t1 + 45)
    finish(res, 'rejoin', role, n0, m0)


if __name__ == '__main__':
    v = sys.argv[1]
    if v in ('spin', 'circle', 'load', 'rejoin'): globals()[v](*sys.argv[2:])
    else: print(__doc__)
